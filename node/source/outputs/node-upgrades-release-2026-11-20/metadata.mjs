import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,cpSync} from 'node:fs';
import {createHash} from 'node:crypto';
const folder='outputs/node-upgrades-release-2026-11-20',repo=folder+'/repo';
const git=(...args)=>execFileSync('git',['-C',repo,'-c','core.safecrlf=false',...args],{maxBuffer:64e6});
const ref=(...args)=>git(...args).toString().trim();
const receipt=JSON.parse(readFileSync(folder+'/publication-receipt.json','utf8'));
assert.equal(ref('rev-parse','HEAD'),receipt.commit);assert.equal(ref('rev-parse','origin/main'),receipt.commit);
for(const file of ['prepare.mjs','finalize.mjs','verify.mjs','record.mjs','metadata.mjs'])cpSync(folder+'/'+file,repo+'/node/source/'+folder+'/'+file);
git('add','-A','--','node');
const changes=ref('diff','--cached','--name-only').split('\n').filter(Boolean);
assert.ok(changes.length&&changes.every(f=>f==='node/source/CHANGELOG.md'||f.startsWith('node/source/docs/changelog/')||f.startsWith('node/source/'+folder+'/')));
assert.equal(ref('diff','--cached','--name-only','--diff-filter=D'),'');
git('-c','user.name=Codex','-c','user.email=codex@users.noreply.github.com','-c','commit.gpgsign=false','commit','-m','Record verified Upgrades publication');
const commit=ref('rev-parse','HEAD');assert.equal(ref('rev-parse',commit+'^'),receipt.commit);
for(const{file,sha256}of receipt.files)assert.equal(createHash('sha256').update(git('cat-file','blob',commit+':node/'+file)).digest('hex'),sha256,file);
assert.equal(ref('status','--porcelain'),'');
const report={commit,base:receipt.commit,destination:'https://github.com/bookskaboo/bookskaboo.github.io.git refs/heads/main',onlyNodeChanged:true,onlyPublicationMetadata:true,runtimeUnchanged:true,canFastForward:true,worktreeClean:true,changedFiles:changes};
writeFileSync(folder+'/metadata-preflight-report.json',JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
